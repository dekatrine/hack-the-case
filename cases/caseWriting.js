function isMarketplaceConversion(item) {
  const description = [item.title, item.caseIntro].filter(Boolean).join(' ');
  return /маркетплейс/i.test(description) && /покупк|конверс|заказ/i.test(description);
}

export function guideCaseRoute(item, route) {
  if (!item || !route.length) return route;
  const marketplace = item.params?.interviewType === 'product_sense' && isMarketplaceConversion(item);
  return route.map(step => {
    const { id } = step;
    let copy = routeCopy[id];
    if (id === 'variant_open') {
      copy = marketplace ? marketplaceOpening : openings[item.params?.interviewType];
    } else if (/^variant_read_[01]$/.test(id)) {
      copy = [step.question, 'Сравни два значения из данных этого шага. Назови группы или периоды и объясни, что означает разница.'];
    } else if (/^variant_gap_[01]$/.test(id)) {
      copy = ['Какой вывод пока рано делать по этим данным?', 'Назови один вывод, который не следует из цифр, и одно сравнение, которого для него не хватает.'];
    } else if (marketplace && id === 'variant_actions') {
      copy = ['Предложи два изменения на выбранном шаге покупки.', 'Для каждого напиши, что изменится на экране или в процессе и почему покупателю будет проще продолжить.'];
    } else if (marketplace && id === 'variant_final') {
      copy = ['Выбери одну функцию или одно изменение для первого запуска. Почему стоит начать именно с него?', 'Опиши, что увидит или сможет сделать покупатель. Приведи один факт из открытых данных и объясни, как проверишь результат.'];
    } else if (id === 'variant_final') {
      copy = [step.question, 'Сначала назови своё решение. Затем укажи один факт из открытых данных, объясни почему он важен и напиши, что сделаешь дальше.'];
    } else if (id === 'skill_checkpoint' && step.hint) {
      copy = [step.question, step.hint];
    }
    if (!copy) return step;
    const [question, answerFormat] = copy;
    return { ...step, question: question.charAt(0).toLocaleUpperCase('ru') + question.slice(1), answerFormat };
  });
}
