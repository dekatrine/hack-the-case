def para(text=None, size=10.5, bold=False, italic=False, color=DARK, align=None, before=0, after=6):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(before); p.paragraph_format.space_after = Pt(after)
    if align: p.alignment = align
    if text:
        r = p.add_run(text); r.bold=bold; r.italic=italic; r.font.size=Pt(size); r.font.color.rgb=color
    return p

def rich(parts, after=6, before=0, size=10.5):
    """parts: list of (text, dict) where dict can have bold/italic/color"""
    p = doc.add_paragraph()
    p.paragraph_format.space_before=Pt(before); p.paragraph_format.space_after=Pt(after)
    for text, fmt in parts:
        r = p.add_run(text)
        r.font.size = Pt(fmt.get('size', size))
        r.bold = fmt.get('bold', False); r.italic = fmt.get('italic', False)
        r.font.color.rgb = fmt.get('color', DARK)
    return p

def bullets(items, size=10.5, after=3):
    for it in items:
        p = doc.add_paragraph(style='List Bullet')
        p.paragraph_format.space_after = Pt(after)
        if isinstance(it, tuple):
            lead, rest = it
            r = p.add_run(lead); r.bold = True; r.font.size=Pt(size); r.font.color.rgb=DARK
            r2 = p.add_run(rest); r2.font.size=Pt(size); r2.font.color.rgb=DARK
        else:
            r = p.add_run(it); r.font.size=Pt(size); r.font.color.rgb=DARK

