def callout(title, body_parts, fill='EAF2FF', bar=BLUE):
    """body_parts: list of (text, fmt) or plain string"""
    t = doc.add_table(rows=1, cols=1); t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = True
    cell = t.cell(0,0); _shade(cell, fill); _set_cell_margins(cell)
    cell.paragraphs[0].text = ''
    if title:
        p = cell.paragraphs[0]; r = p.add_run(title); r.bold=True; r.font.size=Pt(11); r.font.color.rgb=bar
        p.paragraph_format.space_after = Pt(3)
    if isinstance(body_parts, str):
        body_parts = [(body_parts, {})]
    p2 = cell.add_paragraph() if title else cell.paragraphs[0]
    for text, fmt in body_parts:
        r = p2.add_run(text); r.font.size=Pt(fmt.get('size',10)); r.bold=fmt.get('bold',False)
        r.italic=fmt.get('italic',False); r.font.color.rgb=fmt.get('color',DARK)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

def table(headers, rows, widths=None, header_fill='0B4FC2', font=9.0, first_bold=False):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.style = 'Table Grid'
    hdr = t.rows[0].cells
    for i, htext in enumerate(headers):
        _shade(hdr[i], header_fill); _set_cell_margins(hdr[i])
        p = hdr[i].paragraphs[0]; p.paragraph_format.space_after=Pt(0)
        r = p.add_run(htext); r.bold=True; r.font.size=Pt(font); r.font.color.rgb=WHITE
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            _set_cell_margins(cells[i])
            p = cells[i].paragraphs[0]; p.paragraph_format.space_after=Pt(0)
            r = p.add_run(str(val)); r.font.size=Pt(font); r.font.color.rgb=DARK
            if first_bold and i==0: r.bold=True
            if i==0 and first_bold: r.font.color.rgb=BLUE
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after=Pt(2)
    return t

